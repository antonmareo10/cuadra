/**
 * npm run assets [-- --photo] [-- --only=<case>]
 *
 * Draws the documents "as they arrived" for the demo, from the same synthetic data the
 * engine reads (data/world.ts and the PDFs in data/cases):
 *
 *   public/paper/<case>/delivery.jpg        the signed paper copy of the delivery note (flat, for the case page)
 *   public/paper/<case>/delivery-photo.jpg  the same note photographed on the kitchen pass (landing, gallery, video)
 *   public/paper/<case>/invoice.png         the supplier's PDF invoice, page 1
 *   public/paper/<case>/po.png | chat.png   the order: the restaurant's order sheet, or the chef's chat on a phone
 *
 * With --photo it also redraws data/paper/<id>.jpg for cases whose delivery note arrives as a
 * photo. That JPEG is what the engine reads (and what the recording hashes), so it is only
 * redrawn on request: a redrawn photo needs `npm run record -- <id>`.
 *
 * Steps: python scripts/assets/pdf_pages.py (page images + line boxes), then headless Chrome
 * renders the scenes in scripts/assets/scenes. Set BROWSER to a Chromium executable if needed.
 * Nothing here is generated by a model, and nothing is a stock photo: HTML, CSS and SVG only.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import http from "node:http";
import path from "node:path";
import sharp from "sharp";
import { CASES, RESTAURANT, type CaseDefinition } from "../../data/world";
import { launch, sleep } from "../lib/cdp.mjs";

const ROOT = process.cwd();
const PAGES = path.join(ROOT, ".assets", "pages");
const PUBLIC = path.join(ROOT, "public", "paper");
const args = process.argv.slice(2);
const redrawPhoto = args.includes("--photo");
const only = args.find((a) => a.startsWith("--only="))?.slice(7);

interface PrintedLine {
  text: string;
  box: [number, number, number, number];
  size: number;
}
interface Words {
  width: number;
  height: number;
  lines: PrintedLine[];
}

const MONTHS = ["ENE", "FEB", "MAR", "ABR", "MAY", "JUN", "JUL", "AGO", "SEP", "OCT", "NOV", "DIC"];
const stampDate = (ddmmyyyy: string) => {
  const [d, m, y] = ddmmyyyy.split("/");
  return `${d} ${MONTHS[Number(m) - 1]}. ${y}`;
};

function words(caseId: string, doc: string): Words {
  return JSON.parse(fs.readFileSync(path.join(PAGES, `${caseId}-${doc}.words.json`), "utf8"));
}

const isCode = (t: string) => /^[A-Z]{2,4}-\d{2,4}$/.test(t.trim());

/** Ink for a delivery note the kitchen signed: a tick per line, corrections by hand, signature, stamp. */
function deliveryInk(c: CaseDefinition, w: Words) {
  const rows = w.lines.filter((l) => isCode(l.text) && l.box[0] < 60);
  const ticks: { x: number; y: number; s?: number }[] = [];
  const strikes: { x0: number; y0: number; x1: number; y1: number; double?: boolean }[] = [];
  const hand: { x: number; y: number; text: string; size?: number; rot?: number }[] = [];
  for (const row of rows) {
    const line = c.delivery.lines.find((l) => l.product === row.text.trim());
    const cy = (row.box[1] + row.box[3]) / 2;
    const qtyCell = w.lines.find((l) => Math.abs((l.box[1] + l.box[3]) / 2 - cy) < 2 && l.box[2] > 470 && l.box[2] < 485);
    if (line?.handwritten && qtyCell) {
      const [x0, , x1] = qtyCell.box;
      strikes.push({ x0: x0 - 3, y0: cy + 1.6, x1: x1 + 3, y1: cy - 1.2, double: true });
      const [value, ...rest] = line.handwritten.split(" ");
      hand.push({ x: x0 - 32, y: cy + 6.5, text: value, size: 17, rot: -6 });
      const note = rest.join(" ").replace(/[()]/g, "");
      if (note) hand.push({ x: x0 - 92, y: cy + 6, text: note, size: 13.5, rot: -3 });
    } else {
      ticks.push({ x: 527, y: row.box[1] + 8 });
    }
  }
  const received = w.lines.find((l) => l.text.startsWith("Recibido por"));
  const remarks = w.lines.find((l) => l.text.startsWith("OBSERVACIONES"));
  const signature = received ? { x: received.box[2] + 16, y: received.box[3] + 2, text: "Marta Gil", size: 25, rot: -6 } : undefined;
  // The stamp goes on the right, below anything printed in its way.
  let stamp;
  if (remarks) {
    const sx = 372, sw = 150, sh = 60;
    let sy = remarks.box[1] + 2;
    const hits = (y: number) => w.lines.some((l) => l.box[2] > sx - 6 && l.box[0] < sx + sw + 6 && l.box[3] > y - 8 && l.box[1] < y + sh + 8 && l.size > 7);
    while (hits(sy) && sy < 560) sy += 4;
    stamp = { x: sx, y: sy, w: sw, h: sh, rot: -7, lines: [RESTAURANT.name.toUpperCase(), "RECIBIDO", stampDate(c.delivery.date)] };
  }
  return { ticks, strikes, hand, signature, stamp };
}

function serve(): Promise<{ url: string; close: () => void }> {
  const types: Record<string, string> = { ".html": "text/html", ".css": "text/css", ".js": "text/javascript", ".png": "image/png", ".jpg": "image/jpeg", ".ttf": "font/ttf", ".json": "application/json", ".svg": "image/svg+xml" };
  const server = http.createServer((req, res) => {
    const p = decodeURIComponent((req.url ?? "/").split("?")[0]);
    const file = path.join(ROOT, p);
    if (!file.startsWith(ROOT) || !fs.existsSync(file) || !fs.statSync(file).isFile()) {
      res.writeHead(404).end();
      return;
    }
    res.writeHead(200, { "content-type": types[path.extname(file)] ?? "application/octet-stream" });
    fs.createReadStream(file).pipe(res);
  });
  return new Promise((resolve) =>
    server.listen(0, "127.0.0.1", () => {
      const port = (server.address() as { port: number }).port;
      resolve({ url: `http://127.0.0.1:${port}`, close: () => server.close() });
    }),
  );
}

type Browser = Awaited<ReturnType<typeof launch>>;

async function shoot(b: Browser, url: string, scene: string, spec: unknown, size: { w: number; h: number; dsf?: number }, out: string, jpeg?: number) {
  await b.send("Emulation.setDeviceMetricsOverride", { width: size.w, height: size.h, deviceScaleFactor: size.dsf ?? 1, mobile: false });
  await b.send("Page.navigate", { url: `${url}/scripts/assets/scenes/${scene}.html` });
  for (let i = 0; i < 60; i++) {
    await sleep(150);
    if (await b.evaluate("typeof window.renderScene === 'function' && document.readyState === 'complete'")) break;
  }
  const r = (await b.evaluate(`window.renderScene(${JSON.stringify(spec)})`)) as { ok: boolean; w: number; h: number } | undefined;
  if (!r?.ok) throw new Error(`${scene}: fonts did not load (${JSON.stringify(r)})`);
  await sleep(400);
  const shot = (await b.send("Page.captureScreenshot", {
    format: jpeg ? "jpeg" : "png",
    ...(jpeg ? { quality: jpeg } : {}),
    clip: { x: 0, y: 0, width: r.w, height: r.h, scale: 1 },
  })) as { data: string };
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, Buffer.from(shot.data, "base64"));
  console.log("saved", path.relative(ROOT, out));
}

/** A clean page image of a PDF (an invoice or an order sheet arrives as a file, not on paper). */
async function cleanPage(caseId: string, doc: string, out: string) {
  await sharp(path.join(PAGES, `${caseId}-${doc}.png`))
    .resize({ width: 1240 })
    .png({ palette: true, quality: 90, compressionLevel: 9 })
    .toFile(out);
  console.log("saved", path.relative(ROOT, out));
}

/** A phone photo of the top half of the sheet on the kitchen pass, 4:3 landscape. */
function photoScene(kind: "steel" | "wood", seed: number) {
  return {
    w: 1800,
    h: 1350,
    background: kind,
    sheetX: 52,
    sheetY: 84,
    transform: "perspective(2800px) rotateX(7deg) rotateY(-0.8deg) rotateZ(-0.6deg)",
    blurTop: 1.6,
    seed,
  };
}

async function main() {
  execFileSync("python", [path.join("scripts", "assets", "pdf_pages.py")], { stdio: "inherit" });
  const srv = await serve();
  const b = await launch({ width: 1600, height: 2200, port: 9341 });
  try {
    for (const c of CASES) {
      if (only && c.id !== only) continue;
      const dir = path.join(PUBLIC, c.id);
      fs.mkdirSync(dir, { recursive: true });
      const photo = c.delivery.format === "photo";
      const deliveryDoc = photo ? "delivery-printed" : "delivery";
      const w = words(c.id, deliveryDoc);
      const ink = deliveryInk(c, w);
      const page = { src: `/.assets/pages/${c.id}-${deliveryDoc}.png`, wPt: w.width, hPt: w.height };
      const coffee = c.id === "drinks-vat-return" || photo ? { x: 470, y: 430, r: 37 } : null;
      const base = { page, ...ink, coffee, folds: [1 / 3, 2 / 3], paperTone: "#fbf8f1", seed: c.id.length };

      if (!photo) {
        await shoot(b, srv.url, "paper", { ...base, mode: "flat", K: 2 }, { w: 1190, h: 1684 }, path.join(dir, "delivery.jpg"), 84);
      }
      const photoSpec = {
        ...base,
        mode: "photo",
        K: 2.85,
        crumple: photo ? { seed: 7, warp: 11, depth: 4.2 } : { seed: 3, warp: 6, depth: 2.2, freq: "0.004 0.006" },
        scene: photoScene(photo ? "steel" : c.id === "drinks-vat-return" ? "wood" : "steel", c.id.length),
      };
      const photoOut = photo ? path.join(ROOT, "data", "paper", `${c.id}.jpg`) : path.join(dir, "delivery-photo.jpg");
      if (!photo || redrawPhoto) await shoot(b, srv.url, "paper", photoSpec, { w: 1800, h: 1350 }, photoOut, 86);
      if (photo) {
        if (!fs.existsSync(photoOut)) throw new Error(`${c.id}: no photo yet, run npm run assets -- --photo`);
        fs.copyFileSync(photoOut, path.join(dir, "delivery.jpg"));
        fs.copyFileSync(photoOut, path.join(ROOT, "data", "cases", c.id, "delivery.jpg"));
      }

      await cleanPage(c.id, "invoice", path.join(dir, "invoice.png"));
      if (c.po.format === "pdf") await cleanPage(c.id, "po", path.join(dir, "po.png"));
      else {
        const text = fs.readFileSync(path.join(ROOT, "data", "cases", c.id, "po.txt"), "utf8").trimEnd();
        await shoot(b, srv.url, "chat", { text, me: RESTAURANT.chef, date: c.po.date }, { w: 430, h: 760, dsf: 2.5 }, path.join(dir, "chat.png"));
      }
    }
  } finally {
    await b.close();
    srv.close();
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
